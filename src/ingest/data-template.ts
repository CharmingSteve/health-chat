import { TABLES, tableLocation, type ColumnType } from "./schemas.js";

// Builds the CloudFormation template for the Glue database, the Glue tables, and the Athena workgroup.
// The output is JSON, which CloudFormation accepts as YAML. infra/data.yaml is generated from this file.
const GLUE_TYPE: Record<ColumnType, string> = { VARCHAR: "string", DOUBLE: "double", BOOLEAN: "boolean" };
export const DATABASE = "health_chat";
export const RESULTS_PREFIX = "athena-results/";

export function buildDataTemplate(): object {
  const resources: Record<string, object> = {
    GlueDatabase: {
      Type: "AWS::Glue::Database",
      Properties: {
        CatalogId: { Ref: "AWS::AccountId" },
        DatabaseInput: { Name: DATABASE, Description: "health-chat derived tables (Parquet in the tables bucket)" },
      },
    },
    AthenaWorkGroup: {
      Type: "AWS::Athena::WorkGroup",
      Properties: {
        Name: { "Fn::Sub": "${AWS::StackName}" },
        Description: "Read-only queries from health-chat; results expire after 7 days",
        WorkGroupConfiguration: {
          EnforceWorkGroupConfiguration: true,
          PublishCloudWatchMetricsEnabled: true,
          // 1 GiB per query. The tables are about 40 MiB in total, so normal queries are far below this.
          BytesScannedCutoffPerQuery: 1073741824,
          ResultConfiguration: {
            OutputLocation: { "Fn::Sub": `s3://\${TablesBucket}/${RESULTS_PREFIX}` },
            EncryptionConfiguration: { EncryptionOption: "SSE_S3" },
          },
        },
      },
    },
  };
  for (const table of TABLES) {
    resources[`Table${table.name.split("_").map((p) => p[0]!.toUpperCase() + p.slice(1)).join("")}`] = {
      Type: "AWS::Glue::Table",
      Properties: {
        CatalogId: { Ref: "AWS::AccountId" },
        DatabaseName: { Ref: "GlueDatabase" },
        TableInput: {
          Name: table.name,
          Description: table.description,
          TableType: "EXTERNAL_TABLE",
          Parameters: { classification: "parquet", EXTERNAL: "TRUE" },
          StorageDescriptor: {
            Columns: Object.entries(table.columns).map(([Name, type]) => ({ Name, Type: GLUE_TYPE[type] })),
            Location: { "Fn::Sub": `s3://\${TablesBucket}/${tableLocation(table.name)}` },
            InputFormat: "org.apache.hadoop.hive.ql.io.parquet.MapredParquetInputFormat",
            OutputFormat: "org.apache.hadoop.hive.ql.io.parquet.MapredParquetOutputFormat",
            SerdeInfo: { SerializationLibrary: "org.apache.hadoop.hive.ql.io.parquet.serde.ParquetHiveSerDe" },
          },
        },
      },
    };
  }
  return {
    AWSTemplateFormatVersion: "2010-09-09",
    Description: "health-chat: Glue tables over the Parquet files, and a read-only Athena workgroup. Generated by scripts/gen-data-template.ts.",
    Parameters: {
      TablesBucket: { Type: "String", Description: "Bucket holding warehouse/<table>/data.parquet" },
    },
    Resources: resources,
    Outputs: {
      GlueDatabaseName: { Value: { Ref: "GlueDatabase" } },
      AthenaWorkGroupName: { Value: { Ref: "AthenaWorkGroup" } },
    },
  };
}
