import { writeFileSync } from "node:fs";
import { buildDataTemplate } from "../src/ingest/data-template.js";

// Writes infra/data.yaml from the table schemas. Run after changing src/ingest/schemas.ts.
const header = "# GENERATED by scripts/gen-data-template.ts from src/ingest/schemas.ts. Do not edit by hand.\n# The body is JSON, which CloudFormation accepts as YAML.\n";
writeFileSync("infra/data.yaml", header + JSON.stringify(buildDataTemplate(), null, 2) + "\n");
console.info("wrote infra/data.yaml");
